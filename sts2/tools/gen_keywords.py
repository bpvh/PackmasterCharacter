#!/usr/bin/env python3
"""Generate PackmasterCode/Util/Keywords.cs: one BaseLib [CustomEnum] StaticHoverTip per StS1 keyword.

StS1 keywords (Keywordstrings.json) are tooltips. convert_loc.py writes them to static_hover_tips.json as
PACKMASTER-<SLUG>.title/.description; BaseLib resolves a [CustomEnum] StaticHoverTip field named <Pascal> to the
key PACKMASTER-<SLUG>. Cards attach them with WithTip(Keywords.Even).

    python3 tools/gen_keywords.py          # rewrite Keywords.cs from Packmaster/localization/eng/static_hover_tips.json
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from porting import ids  # noqa: E402

STS2 = Path(__file__).resolve().parent.parent
LOC = STS2 / "Packmaster" / "localization" / "eng" / "static_hover_tips.json"
OUT = STS2 / "PackmasterCode" / "Util" / "Keywords.cs"


def pascal(slug: str) -> str:
    return "".join(p[:1] + p[1:].lower() for p in slug.split("_") if p)


def main():
    data = json.loads(LOC.read_text(encoding="utf-8-sig"))
    entries = sorted({k.rsplit(".", 1)[0] for k in data if k.endswith(".title") and k.startswith(ids.MOD_PREFIX)})
    fields = []
    for entry in entries:
        slug = entry[len(ids.MOD_PREFIX):]
        name = pascal(slug)
        if not name or not name[0].isalpha() or ids.slug(name) != slug:
            print(f"skipping {entry}: no field name slugifies back to it", file=sys.stderr)
            continue
        title = data.get(f"{entry}.title", "").replace("\n", " ")
        fields.append((name, title))
    lines = [
        "// <auto-generated> by tools/gen_keywords.py from Packmaster/localization/eng/static_hover_tips.json",
        "// </auto-generated>",
        "using BaseLib.Patches.Content;",
        "",
        "namespace Packmaster.PackmasterCode.Util;",
        "",
        "/// <summary>StS1 keyword tooltips as StaticHoverTips (text in static_hover_tips.json). Use WithTip(Keywords.X).</summary>",
        "public static class Keywords",
        "{",
    ]
    for name, title in fields:
        lines.append(f"    /// <summary>{title.replace('&', '&amp;').replace('<', '&lt;')}</summary>")
        lines.append(f"    [CustomEnum] public static StaticHoverTip {name};")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(fields)} keywords written to {OUT.relative_to(STS2)}")


if __name__ == "__main__":
    main()
